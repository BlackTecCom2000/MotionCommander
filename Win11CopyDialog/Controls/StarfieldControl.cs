        // ── Brush / pen cache ────────────────────────────────────────────────
        private static readonly Brush WhiteBrush = Brushes.White;
        private static readonly Brush WhiteDim   = new SolidColorBrush(Color.FromArgb(200, 255, 255, 255));

        // ── Animation state ──────────────────────────────────────────────────
        // We drive all three layers from a single CompositionTarget.Rendering
        // tick, keeping frame-perfect synchrony across all star layers.

        private double _elapsed1, _elapsed2, _elapsed3;
        private DateTime _lastTick = DateTime.UtcNow;
        private const double CyclePx = 2000.0;   // matches CSS animStar translateY target

        // Storyboard speeds (seconds per full 2000 px cycle)
        private const double Speed1 = 50.0;
        private const double Speed2 = 100.0;
        private const double Speed3 = 150.0;

        // ── Visual children ──────────────────────────────────────────────────
        private readonly DrawingVisual _bgVisual    = new();
        private readonly DrawingVisual _layer1      = new();
        private readonly DrawingVisual _layer1after = new();
        private readonly DrawingVisual _layer2      = new();
        private readonly DrawingVisual _layer2after = new();
        private readonly DrawingVisual _layer3      = new();
        private readonly DrawingVisual _layer3after = new();

        private readonly VisualCollection _children;

        public StarfieldControl()
        {
            _children = new VisualCollection(this)
            {
                _bgVisual,
                _layer1, _layer1after,
                _layer2, _layer2after,
                _layer3, _layer3after
            };

            IsHitTestVisible = false;
            ClipToBounds = true;
            RenderOptions.SetEdgeMode(this, EdgeMode.Aliased);
            UseLayoutRounding = true;

            CompositionTarget.Rendering += OnRendering;
            Unloaded += (_, __) => CompositionTarget.Rendering -= OnRendering;
        }

        // ── Visual tree overrides ────────────────────────────────────────────
        protected override int VisualChildrenCount => _children.Count;
        protected override Visual GetVisualChild(int index) => _children[index];

        protected override void OnRenderSizeChanged(SizeChangedInfo info)
        {
            base.OnRenderSizeChanged(info);
            DrawBackground();
            DrawLayer(_layer1,      Stars1, 1, 0);
            DrawLayer(_layer1after, Stars1, 1, CyclePx);
            DrawLayer(_layer2,      Stars2, 2, 0);
            DrawLayer(_layer2after, Stars2, 2, CyclePx);
            DrawLayer(_layer3,      Stars3, 3, 0);
            DrawLayer(_layer3after, Stars3, 3, CyclePx);
        }

        // ── Rendering tick ───────────────────────────────────────────────────
        private void OnRendering(object? sender, EventArgs e)
        {
            var now = DateTime.UtcNow;
            double dt = (now - _lastTick).TotalSeconds;
            _lastTick = now;

            _elapsed1 = (_elapsed1 + dt * (CyclePx / Speed1)) % CyclePx;
            _elapsed2 = (_elapsed2 + dt * (CyclePx / Speed2)) % CyclePx;
            _elapsed3 = (_elapsed3 + dt * (CyclePx / Speed3)) % CyclePx;

            double sy1 = -_elapsed1;
            double sy2 = -_elapsed2;
            double sy3 = -_elapsed3;

            SetTranslateY(_layer1,      sy1);
            SetTranslateY(_layer1after, sy1 + CyclePx);
            SetTranslateY(_layer2,      sy2);
            SetTranslateY(_layer2after, sy2 + CyclePx);
            SetTranslateY(_layer3,      sy3);
            SetTranslateY(_layer3after, sy3 + CyclePx);
        }

        private static void SetTranslateY(DrawingVisual visual, double y)
        {
            if (visual.Transform is TranslateTransform tt)
                tt.Y = y;
            else
                visual.Transform = new TranslateTransform(0, y);
        }

        // ── Draw helpers ─────────────────────────────────────────────────────

        /// <summary>
        /// Draws the deep-space radial gradient background
        /// (radial-gradient ellipse at bottom, #1b2735 → #090a0f).
        /// </summary>
        private void DrawBackground()
        {
            double w = ActualWidth, h = ActualHeight;
            if (w <= 0 || h <= 0) return;

            using var dc = _bgVisual.RenderOpen();

            var brush = new RadialGradientBrush
            {
                Center        = new Point(0.5, 1.0),
                GradientOrigin= new Point(0.5, 1.0),
                RadiusX = 0.8,
                RadiusY = 0.8,
                MappingMode = BrushMappingMode.RelativeToBoundingBox,
                GradientStops = new GradientStopCollection
                {
                    new(Color.FromRgb(0x1b, 0x27, 0x35), 0.0),
                    new(Color.FromRgb(0x09, 0x0a, 0x0f), 1.0)
                }
            };
            brush.Freeze();
            dc.DrawRectangle(brush, null, new Rect(0, 0, w, CyclePx * 2));
        }

        /// <summary>
        /// Renders all star dots for one layer onto a DrawingVisual.
        /// <paramref name="offsetY"/> is 0 for the primary canvas, CyclePx for the :after clone.
        /// </summary>
        private static void DrawLayer(
            DrawingVisual visual,
            (double x, double y)[] stars,
            double size,
            double offsetY)
        {
            using var dc = visual.RenderOpen();

            double half = size / 2.0;
            foreach (var (sx, sy) in stars)
            {
                dc.DrawRectangle(
                    WhiteBrush, null,
                    new Rect(sx - half, sy + offsetY - half, size, size));
            }
        }
