/// <para><b>Назначение.</b> Справочник расшифровывает ТОЛЬКО реально
/// прочитанные сырые значения: подставляются только имена, описания и
/// правила форматирования. Никакие показатели отсюда не выдумываются.</para>
///
/// <para><b>Почему идентификаторы десятичные.</b> Раньше здесь стояли
/// шестнадцатеричные литералы с префиксом 0x: 0xC5 — это 197, а не 5.
/// Из-за этого атрибуты 187, 188, 194 и 197 не находились в справочнике,
/// получали пустое имя и отбрасывались при разборе. Итог: накопитель
/// показывал «S.M.A.R.T. недоступен», хотя данные читались полностью —
/// пропадали ровно те атрибуты, по которым оценивают состояние носителя
/// (температура, ожидающие и неустранимые секторы).</para>
///
/// <para>Спецификация ATA публикует эти номера десятичными, и теперь
