using System.Globalization;

namespace Win11CopyDialog.Modules.StorageControlCenter.Services;

/// <summary>
/// Справочник идентификаторов S.M.A.R.T. (ATA и NVMe).
///
/// <para>Используется ТОЛЬКО для расшифровки реально прочитанных сырых значений.
/// Никаких значений отсюда не подставляются в диск — только имена, описания
/// и правила форматирования.</para>
///
/// <para>Важно: наборы ATA (0x01–0xF2) и NVMe (SMART Information) в основном
/// не пересекаются, но у обоих есть 0x01 и 0x05. Здесь используется единая
/// таблица с приоритетом ATA как более информативного, а NVMe-специфичные
/// атрибуты обрабатываются в ветке 0x02/0x03/0x04/0x05 при описании.</para>
/// </summary>
public static class SmartAttributeCatalog
{
    public static string GetName(byte id) => id switch
    {
        0x01 => "Ошибки чтения",
        0x02 => "Температура",
        0x03 => "Время до полного сброса (Spin-up)",
        0x04 => "Запуски шпинделя",
        0x05 => "Переназначенные секторы (Reallocated)",
        0x07 => "Сектора с ошибкой поиска (Seek)",
        0x09 => "Часы работы",
        0x0A => "Запуски шпинделя",
        0x0C => "Циклы включения питания",
        0x0E => "Ошибки вращения",
        0x0F => "Небезопасные выключения",
        0xC0 => "Отказы чтения/записи из-за потери питания",
        0xC2 => "Температура",
        0xC5 => "Ожидающие секторы (Pending)",
        0xC6 => "Некорректируемые секторы (Uncorrectable)",
        0xE7 => "Оставшийся ресурс SSD",
        0xE9 => "Счётчик событий носителя",
        0xF1 => "Записанные секторы",
        0xF2 => "Прочитанные секторы",
        _ => ""
    };

    public static string GetDescription(byte id) => id switch
    {
        0x05 => "Секторы, переназначенные из-за ошибки. Ненулевое значение указывает на износ носителя.",
        0x07 => "Сектора с ошибкой позиционирования головок.",
        0x09 => "Полное время работы накопителя в часах.",
        0x0C => "Количество циклов включения питания.",
        0x0F => "Количество аварийных выключений без корректного сброса.",
        0xC0 => "Потери питания при записи, приведшие к потере данных.",
        0xC2 => "Текущая температура накопителя.",
        0xC5 => "Секторы, ожидающие переназначения. Ненулевое значение — тревожный признак.",
        0xC6 => "Секторы с неустранимой ошибкой. Ненулевое значение означает потерю данных.",
        0xE7 => "Оставшийся ресурс твердотельного накопителя в процентах.",
        0xF1 => "Общее число записанных секторов за весь срок службы.",
        0xF2 => "Общее число прочитанных секторов за весь срок службы.",
        _ => ""
    };

    /// <summary>
    /// Атрибут критический по смыслу: ненулевое значение означает
    /// начинающуюся деградацию носителя.
    /// </summary>
    public static bool IsCriticalAttribute(byte id) => id is
        0x05 or   // Reallocated Sectors Count
        0xC5 or   // Current Pending Sector
        0xC6 or   // Offline Uncorrectable Sector
        0xC0;     // Power Failure / Retract Count

    /// <summary>Форматирует «сырое» значение с учётом специфики атрибута.</summary>
    public static string FormatRawValue(byte id, long raw) => id switch
    {
        0xC2 => $"{raw / 10.0:F0} °C",      // ATA: температура в десятых долях градуса
        0x03 or 0x04 => $"{raw}%",          // NVMe: проценты
        0xC0 => $"{raw:N0}",
        _ => raw.ToString("N0", CultureInfo.InvariantCulture)
    };
}
