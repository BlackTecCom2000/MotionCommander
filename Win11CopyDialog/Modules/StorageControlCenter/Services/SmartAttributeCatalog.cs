    /// <summary>
    /// Атрибут критический по смыслу: ненулевое значение означает
    /// начинающуюся деградацию носителя.
    /// </summary>
    /// <remarks>
    /// Прежние значения 0x05, 0xC5, 0xC6, 0xC0 обозначали 5, 197, 198 и
    /// 192, то есть атрибут 199 (ошибки CRC интерфейса) и 187
    /// (неустранимые секторы) критическими не считались вовсе.
    /// </remarks>
    public static bool IsCriticalAttribute(byte id) => id is
        5 or      // Reallocated Sectors Count
        187 or    // Reported Uncorrect
        196 or    // Reallocated Event Count
        197 or    // Current Pending Sector
        198 or    // Offline Uncorrectable Sector
        199;      // UDMA CRC Error Count (указывает на кабель, а не носитель)

    /// <summary>
    /// Форматирует сырое значение с учётом специфики атрибута.
    /// </summary>
    /// <remarks>
    /// Атрибут 194 хранит температуру в градусах Цельсия, а 190 и 235 —
    /// в десятых долях. Раньше форматирование стояло на 0xC2 (=194) и
    /// всегда делило на 10, из-за чего 34 °C показывались как 3 °C.
    /// </remarks>
    public static string FormatRawValue(byte id, long raw) => id switch
    {
        194 => $"{raw} °C",
        190 or 235 => $"{raw / 10.0:F0} °C",
        202 or 231 or 233 => $"{raw} %",
        _ => raw.ToString("N0", CultureInfo.InvariantCulture)
    };
}
